#!/usr/bin/env node
/**
 * generate-sitemap.mjs — write public/sitemap.xml and public/robots.txt.
 *
 * WHY THIS EXISTS
 * ---------------
 * Measured against the live site on 2026-11-13:
 *
 *     GET https://dumuwaks.co.ke/sitemap.xml   ->  HTTP 200, and it is the
 *                                                  SPA's index.html.
 *                                                  0 <loc> elements.
 *
 * The site is a single-page app served by nginx `try_files`, so EVERY
 * unmatched path renders the application — including /sitemap.xml. The status
 * code is 200, which is why nothing noticed: a checker that looks only at the
 * status sees a healthy sitemap. There isn't one.
 *
 * robots.txt made it worse by naming no `Sitemap:` line at all, so a crawler
 * had nothing to follow and no reason to look.
 *
 * A sitemap DOES exist in this repository — seo/src/app/sitemap.ts, a proper
 * dynamic Next.js route that even enumerates technician pages from the API.
 * It is just not what answers at dumuwaks.co.ke/sitemap.xml, which is the
 * canonical path and the one in every crawler's convention.
 *
 * WHY A BUILD-TIME FILE RATHER THAN ROUTING TO THE seo/ APP
 * ---------------------------------------------------------
 * Routing /sitemap.xml to the Next app would work and is a bigger change: it
 * needs an nginx location block deployed in step with this build, and it puts
 * a runtime dependency (the Next app being up, and its API fetch succeeding)
 * in front of a file crawlers ask for constantly. A static file in
 * public/ is served by nginx directly, cannot 500, and ships with the SPA it
 * describes.
 *
 * The two are complements, not rivals: this covers the SPA's own public
 * routes; seo/sitemap.ts covers the content site's.
 *
 * WHAT IS IN IT, AND WHAT IS DELIBERATELY NOT
 * -------------------------------------------
 * Only routes that a signed-out visitor can actually open, taken from the
 * app's own router. Authenticated and admin routes are excluded AND
 * Disallow'd in robots.txt: /admin, /dashboard, /bookings, /messages,
 * /preferences, /settings, /saved-posts, /profile/:id, /login, /register.
 *
 * Dynamic routes — /posts/:postId and /profile/:id — are NOT listed. They
 * need the API to enumerate, which is exactly the runtime dependency this
 * file avoids, and a sitemap listing URLs that 404 is worse than one that
 * omits them. seo/src/app/sitemap.ts is where dynamic enumeration belongs.
 *
 * Run by `npm run build` (prebuild), so it cannot be forgotten.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const PUBLIC = resolve(HERE, '..', 'public');
const SITE = process.env.SITE_URL || 'https://dumuwaks.co.ke';

// path, changefreq, priority — each one checked against frontend/src's router.
const PUBLIC_ROUTES = [
  ['/', 'weekly', '1.0'],
  ['/find-technicians', 'daily', '0.9'],
  ['/how-it-works', 'monthly', '0.8'],
  ['/faq', 'monthly', '0.8'],
  ['/about', 'monthly', '0.7'],
  ['/book', 'weekly', '0.8'],
  ['/careers', 'monthly', '0.5'],
  ['/donate', 'monthly', '0.4'],
  ['/install-app', 'monthly', '0.3'],
  ['/privacy', 'yearly', '0.3'],
];

// Routes a signed-out visitor cannot use, or must not be indexed.
const PRIVATE_ROUTES = [
  '/admin',
  '/dashboard',
  '/bookings',
  '/messages',
  '/preferences',
  '/settings',
  '/saved-posts',
  '/profile',
  '/login',
  '/register',
  '/booking-flow',
  '/booking/create',
];

const today = new Date().toISOString().slice(0, 10);

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by frontend/scripts/generate-sitemap.mjs. Do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${PUBLIC_ROUTES.map(
  ([path, freq, priority]) => `  <url>
    <loc>${SITE}${path === '/' ? '/' : path}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${freq}</changefreq>
    <priority>${priority}</priority>
  </url>`
).join('\n')}
</urlset>
`;

const robots = `# Dumuwaks — dumuwaks.co.ke
# Generated by frontend/scripts/generate-sitemap.mjs. Do not edit by hand.
#
# The SPA is served by nginx try_files, so every unmatched path renders the
# application with HTTP 200 — including /sitemap.xml, which is why this site
# appeared to have a sitemap for months and did not. The sitemap is now a real
# static file in public/, written by the same script as this robots.txt so the
# two cannot disagree.
#
# The content site's own sitemap lives in the seo/ Next app
# (seo/src/app/sitemap.ts) and covers its pages, including technician profiles
# enumerated from the API.
User-agent: *
Allow: /

# Signed-in and admin surfaces. Excluded from the sitemap as well.
${PRIVATE_ROUTES.map((p) => `Disallow: ${p}`).join('\n')}

Sitemap: ${SITE}/sitemap.xml
`;

mkdirSync(PUBLIC, { recursive: true });
writeFileSync(resolve(PUBLIC, 'sitemap.xml'), sitemap);
writeFileSync(resolve(PUBLIC, 'robots.txt'), robots);
console.log(
  `generate-sitemap: ${PUBLIC_ROUTES.length} public route(s) -> public/sitemap.xml, ` +
    `${PRIVATE_ROUTES.length} disallowed -> public/robots.txt`
);
